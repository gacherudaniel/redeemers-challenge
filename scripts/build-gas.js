#!/usr/bin/env node
/*
 * Builds the Apps Script copy of the project in apps-script/ from the GitHub Pages files,
 * so there is only one set of sources to edit.
 *
 *   node scripts/build-gas.js          write the files
 *   node scripts/build-gas.js --check  exit 1 if apps-script/ is out of date
 *
 * Generated:
 *   Index.html / Admin.html     the two pages, with styles and scripts pulled in by include()
 *   Styles.html / AdminStyles.html
 *   Client.html / AdminClient.html   every script the page needs, in order
 *   Shared.gs                   the rules the server shares with the browser
 *   Content.gs                  The Redeemer's Challenge content and answer key
 * Hand-written: Code.gs, Hub.gs, appsscript.json.
 *
 * The quiz content (questions.js) and the Team Showdown question bank are deliberately
 * left out of the page bundles: participants get quiz content from the server only while
 * the quiz is visible, and never get Team Showdown answers.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const outDir = path.join(root, 'apps-script');
const NOTE = 'Generated by `npm run build:gas` from the project files. Edit those, not this one.';
const SERVER_ONLY = ['questions.js', 'games/showdown-questions.js'];
const SHARED_GS = ['shared/rng.js', 'games/showdown-questions.js', 'shared/defaults.js', 'shared/session-core.js', 'games/rush-core.js', 'games/road-core.js', 'games/showdown-core.js'];
const STALE = ['AnswerKey.gs', 'Config.html', 'Questions.html', 'Engine.html', 'Backend.html', 'Game.html'];

const read = (file) => fs.readFileSync(path.join(root, file), 'utf8');

function guard(file, text, pattern) {
  if (pattern.test(text)) throw new Error(file + ' contains ' + pattern + ', which would break the Apps Script build.');
}

function replaceOnce(text, find, replacement, file) {
  const count = text.split(find).length - 1;
  if (count !== 1) throw new Error('Expected exactly one "' + find + '" in ' + file + ', found ' + count + '.');
  return text.replace(find, () => replacement);
}

/** Local <script src> files in page order. */
function scriptsOf(html) {
  const out = [];
  const re = /<script src="([^"]+)"><\/script>/g;
  let m;
  while ((m = re.exec(html))) if (!/^https?:/.test(m[1])) out.push(m[1]);
  return out;
}

function bundle(files) {
  return '<script>\n/* ' + NOTE + ' */\n' + files.map((f) => {
    const js = read(f);
    guard(f, js, /<\/script/i);
    return '\n/* ── ' + f + ' ── */\n' + js;
  }).join('\n') + '</script>\n';
}

function page(file, styles, client, bodyAttrs) {
  let html = read(file);
  guard(file, html, /<\?/);
  styles.forEach(([href, name]) => {
    html = replaceOnce(html, '<link rel="stylesheet" href="' + href + '">', "<?!= include('" + name + "'); ?>", file);
  });
  const scripts = scriptsOf(html);
  scripts.forEach((src, i) => {
    html = replaceOnce(html, '<script src="' + src + '"></script>', i === 0 ? "<?!= include('" + client + "'); ?>" : '', file);
  });
  html = html.replace(/\n\s*\n(\s*<\/body>)/, '\n$1');
  // Apps Script sets the viewport itself (addMetaTag in Code.gs) and ignores this tag.
  html = html.replace(/\s*<meta name="viewport"[^>]*>/, '');
  html = replaceOnce(html, '<body', '<body ' + bodyAttrs, file);
  html = replaceOnce(html, '<!doctype html>', '<!doctype html>\n<!-- ' + NOTE + ' -->', file);
  return { html, scripts };
}

function style(file) {
  const css = read(file);
  guard(file, css, /<\/style/i);
  return '<style>\n/* ' + NOTE + ' */\n' + css + '</style>\n';
}

function content() {
  const c = require(path.join(root, 'questions.js'));
  const ids = new Set();
  const key = c.questions.map((q) => {
    if (!q.id || ids.has(q.id)) throw new Error('Question ids must be unique: ' + q.id);
    ids.add(q.id);
    if (!Number.isInteger(q.answer) || q.answer < 0 || q.answer >= q.choices.length) throw new Error('Question "' + q.id + '" has an invalid answer index.');
    if (q.choices.length < 2 || q.choices.length > 4) throw new Error('Question "' + q.id + '" needs 2–4 choices.');
    return { id: q.id, answer: q.answer, choices: q.choices.length };
  });
  return (
    '// ' + NOTE + '\n' +
    '// The Redeemer’s Challenge content (sent to players only while the quiz is visible)\n' +
    '// and its answer key (used to check shared-leaderboard scores).\n' +
    'const REDEEMER_CONTENT = ' + JSON.stringify(c, null, 2) + ';\n\n' +
    'const QUESTION_KEY = ' + JSON.stringify(key, null, 2) + ';\n'
  );
}

function sharedGs() {
  return '// ' + NOTE + '\n// The rules the server shares with the browser, so both apply them identically.\n' + SHARED_GS.map((f) => '\n// ── ' + f + ' ──\n' + read(f)).join('\n');
}

function build() {
  const files = {};
  const participant = page('index.html', [['styles.css', 'Styles']], 'Client', 'data-app-url="<?= appUrl ?>" data-session="<?= session ?>" data-mode="<?= mode ?>" data-game="<?= game ?>" data-preview="<?= preview ?>"');
  const admin = page('admin.html', [['styles.css', 'Styles'], ['admin.css', 'AdminStyles']], 'AdminClient', 'data-app-url="<?= appUrl ?>"');
  files['Index.html'] = participant.html;
  files['Admin.html'] = admin.html;
  files['Styles.html'] = style('styles.css');
  files['AdminStyles.html'] = style('admin.css');
  files['Client.html'] = bundle(participant.scripts.filter((f) => SERVER_ONLY.indexOf(f) < 0));
  files['AdminClient.html'] = bundle(admin.scripts.filter((f) => SERVER_ONLY.indexOf(f) < 0));
  files['Shared.gs'] = sharedGs();
  files['Content.gs'] = content();
  return files;
}

const files = build();
const check = process.argv.includes('--check');
const stale = [];
for (const [name, text] of Object.entries(files)) {
  const target = path.join(outDir, name);
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
  if (current === text) continue;
  if (check) stale.push(name);
  else fs.writeFileSync(target, text);
}
for (const name of STALE) {
  const target = path.join(outDir, name);
  if (!fs.existsSync(target)) continue;
  if (check) stale.push(name + ' (old file, delete it)');
  else fs.unlinkSync(target);
}
if (check && stale.length) {
  console.error('apps-script/ is out of date (' + stale.join(', ') + '). Run: npm run build:gas');
  process.exit(1);
}
if (!check) console.log('Apps Script files written to apps-script/: ' + Object.keys(files).join(', '));
